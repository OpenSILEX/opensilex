package org.opensilex.aiimport.service;

import org.opensilex.aiimport.workbook.WorkbookStructure;

import java.util.UUID;

/**
 * One file of a conversation, as it was read. The conversation holds the files in the order they
 * were added and works on the sheets of all of them together.
 *
 * @author Arnaud Charleroy
 */
public class SessionFile {

    private final String id;
    private final String name;
    private final WorkbookStructure structure;

    /**
     * @param id the identifier the stored copy of the file carries; generated by the server, never
     *           taken from what the user sent, since it makes up a path
     */
    public SessionFile(String id, String name, WorkbookStructure structure) {
        this.id = id;
        this.name = name;
        this.structure = structure;
    }

    public static SessionFile of(String name, WorkbookStructure structure) {
        return new SessionFile(UUID.randomUUID().toString(), name, structure);
    }

    public String getId() {
        return id;
    }

    /**
     * @return the name the user gave the file
     */
    public String getName() {
        return name;
    }

    public WorkbookStructure getStructure() {
        return structure;
    }
}
